#!/bin/bash
# SPDX-License-Identifier: GPL-2.0-only
# Builds boot/koa2's execute candidate (koa2_handoff_exec.ko): the staging
# source plus exec.c and the real jump.S, which arms the trampoline for a
# quiesce dry-run but still does not jump (ports/koa2/handoff-quiesce.md). Host
# only: it loads nothing and touches no device. Same target-lock.h derivation
# as build-handoff-module.sh; the gates differ (jump.S is allowed its CP15
# writes, but only inside the trampoline blob, and Gate 3 is mandatory).
#
# usage: build-exec-module.sh KERNEL_SRC KERNEL_OUT PAYLOAD_OUT [DEST]
set -euo pipefail
[[ $# -ge 3 ]] || { echo "usage: $0 KERNEL_SRC KERNEL_OUT PAYLOAD_OUT [DEST]" >&2; exit 2; }
src=$1 out=$2 payload=$3 dest=${4:-$HOME/artifacts/koa2-handoff-exec}
here=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/../.." && pwd)
tc=$HOME/toolchains/aosp-arm-gcc49/bin/arm-linux-androidkernel-
nm=$HOME/toolchains/aosp-arm-gcc49/bin/arm-linux-androideabi-gcc-nm
work=$(mktemp -d); trap 'rm -rf "$work"' EXIT
cp "$here"/boot/koa2/{Kbuild,stage.c,exec.c,stage-abi.h,contract.c,contract.h,plan.c,plan.h,fdt-rewrite.c,fdt-rewrite.h,copylist.c,copylist.h,quiesce-verify.c,quiesce-verify.h,marker.c,marker.h,jump.S,jump-abi.h,jump-params.c,jump-params.h,koa2-types.h} "$work/"
cp "$here"/boot/handoff/{sha256.c,sha256.h} "$work/"
fp=$(python3 "$here/ports/koa2/derive-kernel-footprint.py" "$payload")
zimage=$payload/arch/arm/boot/zImage
python3 - "$fp" "$zimage" "$work/target-lock.h" <<'PY'
import hashlib, json, sys
fp = json.loads(sys.argv[1]); data = open(sys.argv[2], 'rb').read()
assert len(data) == fp['zimage_size']
digest = ','.join('0x%02x' % b for b in hashlib.sha256(data).digest())
bootargs = 'console=ttymxc0,115200 no_console_suspend rdinit=/init koa2_smoke_hold=20 koa2_smoke_wdt=30'
open(sys.argv[3], 'w').write(f'''/* Generated by ports/koa2/build-exec-module.sh. */
#ifndef KOA2_TARGET_LOCK_H
#define KOA2_TARGET_LOCK_H
#define K2S_STOCK_RELEASE "4.1.15-lab126"
#define K2S_STOCK_MACHINE "armv7l"
#define K2S_STOCK_VERSION "#1 SMP PREEMPT Tue Aug 1 11:50:12 UTC 2023"
#define K2S_KERNEL_BYTES {fp['zimage_size']}u
#define K2S_KERNEL_SHA256 {{{digest}}}
#define K2S_ZRELADDR {fp['zreladdr']}u
#define K2S_KERNEL_END {fp['kernel_end']}u
#define K2S_ZIMAGE_RUNTIME {fp['zimage_runtime']}u
#define K2S_BOOTARGS "{bootargs}"
#define K2S_HAS_INITRAMFS 1
#endif
''')
PY
export ARCH=arm CROSS_COMPILE="$tc" KCFLAGS='-fno-pic -fno-pie'
make -C "$src" O="$out" M="$work" KOA2_EXEC=1 modules > "$work/build.log" 2>&1 || { cat "$work/build.log" >&2; exit 1; }
ko=$work/koa2_handoff_exec.ko
# Gate 1: every import exists in the tree it was built against, and no GOT.
undefined=$("$nm" -u "$ko" | awk '{print $2}')
for s in $undefined; do
    [[ $s == _GLOBAL_OFFSET_TABLE_ ]] && { echo "Refusing: module needs a GOT (built as PIC)" >&2; exit 2; }
    awk -v s="$s" -F'\t' '$2==s{f=1} END{exit !f}' "$out/Module.symvers" || { echo "Refusing: $s not exported" >&2; exit 2; }
done
# Gate 2: the only coprocessor writes allowed are jump.S's own, and only a
# dry-run -- so nothing may branch into the trampoline either. Every mcr/mcrr
# in the disassembly must have an address inside [koa2_jump_start,
# koa2_jump_end); any outside is a CP15 write the execute path must not make.
python3 - "$ko" <<'PY'
import re, subprocess, sys
ko = sys.argv[1]
nm = subprocess.run(['arm-linux-gnueabi-nm', ko], capture_output=True, text=True, check=True).stdout
sym = {}
for line in nm.splitlines():
    f = line.split()
    if len(f) == 3:
        sym[f[2]] = int(f[0], 16)
if 'koa2_jump_start' not in sym or 'koa2_jump_end' not in sym:
    sys.exit('Refusing: trampoline symbols absent; jump.S not linked as expected')
# jump.S lives in its own section; nm gives section-relative values, so bound
# the check by the .text offsets objdump prints for the trampoline labels.
dis = subprocess.run(['arm-linux-gnueabi-objdump', '-d', ko], capture_output=True, text=True, check=True).stdout
lo = hi = None
cur = None
bad = []
label = re.compile(r'^([0-9a-f]+) <(koa2_jump_start|koa2_jump_end|koa2_jump_params)>:')
insn = re.compile(r'^\s*([0-9a-f]+):\s+[0-9a-f ]+\s+(mcrr?2?)\b')
# objdump resets the address counter per section; track the section each label
# and instruction belongs to by remembering the most recent section header.
section = None
sec = re.compile(r'^Disassembly of section (\S+):')
marks = {}
for line in dis.splitlines():
    m = sec.match(line)
    if m:
        section = m.group(1); continue
    m = label.match(line)
    if m:
        marks[m.group(2)] = (section, int(m.group(1), 16)); continue
    m = insn.match(line)
    if m:
        bad.append((section, int(m.group(1), 16), m.group(2)))
if 'koa2_jump_start' not in marks or 'koa2_jump_end' not in marks:
    sys.exit('Refusing: trampoline bounds not found in disassembly')
jsec, jstart = marks['koa2_jump_start']
esec, jend = marks['koa2_jump_end']
if jsec != esec:
    sys.exit('Refusing: trampoline start and end in different sections')
outside = [(s, a, op) for (s, a, op) in bad if not (s == jsec and jstart <= a < jend)]
if outside:
    for s, a, op in outside:
        print(f'Refusing: {op} at {s}+0x{a:x} is a coprocessor write outside the trampoline', file=sys.stderr)
    sys.exit(2)
# Nothing may branch into the trampoline: this batch only copies it. A call or
# jump relocation against a trampoline symbol, or a branch instruction outside
# the blob whose target lies inside it, is a jump the dry-run must not have.
rel = subprocess.run(['arm-linux-gnueabi-readelf', '-rW', ko], capture_output=True, text=True, check=True).stdout
for line in rel.splitlines():
    if re.search(r'koa2_jump_(start|end|params)', line) and not re.search(r'R_ARM_(MOVW_ABS_NC|MOVT_ABS|ABS32)', line):
        sys.exit('Refusing: non-address relocation against the trampoline: ' + line.strip())
branch = re.compile(r'^\s*([0-9a-f]+):\s+[0-9a-f ]+\s+(bl?x?|b\.?\w*)\s+([0-9a-f]+)\s')
section = None
for line in dis.splitlines():
    m = sec.match(line)
    if m:
        section = m.group(1); continue
    m = branch.match(line)
    if m and section == jsec:
        at, target = int(m.group(1), 16), int(m.group(3), 16)
        if not (jstart <= at < jend) and jstart <= target < jend:
            sys.exit(f'Refusing: branch at {section}+0x{at:x} into the trampoline')
print(f'Gate 2: {len(bad)} coprocessor writes, all inside the trampoline [{jsec} 0x{jstart:x},0x{jend:x}); no branch into it')
PY
# No symbol that stops a core, restarts, leaves the kernel, or resolves symbols
# by name. The trampoline is entered only by a real jump, which this batch does
# not build; reaching it any other way is refused by Gate 2 above.
for s in $undefined; do
    case $s in cpu_down|machine_restart|kernel_restart|emergency_restart|machine_halt|soft_restart|cpu_reset|disable_nonboot_cpus|__dump_lastk_to_mmc|kallsyms_lookup_name)
        echo "Refusing: execute module imports $s" >&2; exit 2 ;;
    esac
done
# Gate 3 is mandatory here: the execute module adds imports (cpu_online_mask)
# the staging module did not, and it must not reach a device whose stock loader
# would reject its versions. No stock modules, no build.
[[ -n ${KOA2_STOCK_MODULES:-} ]] || { echo "Refusing: KOA2_STOCK_MODULES is required to build the execute module" >&2; exit 2; }
python3 "$here/ports/koa2/module-crcs.py" check --stock "$KOA2_STOCK_MODULES" --symvers "$out/Module.symvers" "$ko" > "$work/crcs.json"     || { cat "$work/crcs.json" >&2; echo "Refusing: stock kernel would reject this module's versions" >&2; exit 2; }
mkdir -p "$dest"
cp "$work/crcs.json" "$dest/"
cp "$ko" "$work/target-lock.h" "$dest/"
arm-linux-gnueabi-readelf -p .modinfo "$ko" | grep -o 'vermagic=.*' > "$dest/vermagic.txt"
echo "$undefined" > "$dest/imports.txt"
(cd "$dest" && sha256sum koa2_handoff_exec.ko target-lock.h > SHA256SUMS)
echo "built $dest/koa2_handoff_exec.ko ($(wc -l < "$dest/imports.txt") imports, $(cat "$dest/vermagic.txt"))"
